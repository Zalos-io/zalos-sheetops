"""Frozen synthetic read/CSV/finance regression benchmark, with isolated workers.

Prepare once, then run baseline and candidate against the same manifest. Expected
results are authored from fixture inputs, never generated by a SheetOps reader.
Reserved variants exercise the same contracts with different data; they are not a
public dataset or evidence of broad financial task performance.
"""

import argparse
import csv
import hashlib
import json
import os
import statistics
import subprocess
import sys
import time
from datetime import datetime
from decimal import localcontext
from pathlib import Path


def grade(expected: dict, observed: dict) -> bool:
    return observed == expected


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def prepare(root: Path) -> None:
    from openpyxl import Workbook

    root.mkdir(parents=True, exist_ok=False)
    cases = []
    for split, count in [("development", 1000), ("reserved", 3127)]:
        prefix = split + "-"
        header = ["reference", "amount", "note"]
        records = [
            [f"{i:018d}", f"{i}.25", "quoted\nline" if i == 1 else "café"]
            for i in range(1, count + 1)
        ]
        for label, encoding, delimiter in [
            ("utf8", "utf-8-sig", ","),
            ("utf16", "utf-16", "\t"),
            ("utf32", "utf-32", ";"),
        ]:
            filename = prefix + label + ".csv"
            with (root / filename).open("w", encoding=encoding, newline="") as stream:
                csv.writer(stream, delimiter=delimiter).writerows([header, *records])
            expected = {
                "rows": count,
                "first": dict(zip(header, records[0])),
                "lastId": records[-1][0],
                "sourceRowsStart": [2, 4],
                "truncated": False,
                "rowCount": count,
            }
            cases.append(
                {
                    "id": prefix + label,
                    "split": split,
                    "operation": "csv",
                    "file": filename,
                    "delimiter": delimiter,
                    "expected": {"data": expected},
                }
            )
        cases.append(
            {
                "id": prefix + "csv-preview",
                "split": split,
                "operation": "csv",
                "file": prefix + "utf8.csv",
                "delimiter": ",",
                "maxRows": 2,
                "expected": {
                    "data": {
                        "rows": 2,
                        "first": dict(zip(header, records[0])),
                        "lastId": records[1][0],
                        "sourceRowsStart": [2, 4],
                        "truncated": True,
                        "rowCount": None,
                    }
                },
            }
        )
        for extra in [False, True]:
            filename = prefix + ("unheaded.xlsx" if extra else "typed.xlsx")
            workbook = Workbook()
            sheet = workbook.active
            sheet.title = "Ledger"
            sheet.append(["reference", "amount", "date"])
            sheet.append(
                [
                    records[0][0],
                    10.25,
                    datetime(2026, 6, 30),
                    *(["99.00"] if extra else []),
                ]
            )
            sheet["C2"].number_format = "yyyy-mm-dd"
            workbook.save(root / filename)
            expected = (
                {"errorCode": "table_width_mismatch"}
                if extra
                else {
                    "data": {
                        "headers": ["reference", "amount", "date"],
                        "rows": [[records[0][0], "10.25", "2026-06-30 00:00:00"]],
                        "rowCount": 1,
                    }
                }
            )
            cases.append(
                {
                    "id": prefix + ("unheaded" if extra else "typed"),
                    "split": split,
                    "operation": "table",
                    "file": filename,
                    "expected": expected,
                }
            )
        base = {"rows": [{"reference": records[0][0], "amount": "10.00"}]}
        recon_cases = [
            (
                "matched",
                base,
                base,
                {
                    "data": {
                        "summary": {
                            "matched": 1,
                            "leftUnmatched": 0,
                            "rightUnmatched": 0,
                            "variance": 0,
                        },
                        "variance": [],
                    }
                },
            ),
            (
                "preview",
                {**base, "truncated": True, "rowCount": None},
                base,
                {"errorCode": "incomplete_population"},
            ),
            (
                "blank-key",
                {
                    "rows": [
                        {
                            "reference": "\t " if split == "reserved" else "",
                            "amount": "10",
                        }
                    ]
                },
                base,
                {"errorCode": "invalid_key_value"},
            ),
            (
                "unmatched-invalid",
                {
                    "rows": [
                        {
                            "reference": "bad",
                            "amount": "NaN" if split == "development" else "-Infinity",
                        }
                    ]
                },
                base,
                {"errorCode": "invalid_field"},
            ),
            (
                "high-precision",
                {"rows": [{"reference": "a", "amount": "10000.12345"}]},
                {"rows": [{"reference": "a", "amount": "10000.00000"}]},
                {
                    "data": {
                        "summary": {
                            "matched": 0,
                            "leftUnmatched": 0,
                            "rightUnmatched": 0,
                            "variance": 1,
                        },
                        "variance": [
                            {
                                "key": {"reference": "a"},
                                "leftAmount": "10000.12345",
                                "rightAmount": "10000.00000",
                                "difference": "0.12345",
                            }
                        ],
                    }
                },
            ),
        ]
        for label, left, right, expected in recon_cases:
            cases.append(
                {
                    "id": prefix + label,
                    "split": split,
                    "operation": "reconcile",
                    "left": left,
                    "right": right,
                    "contextPrecision": 3 if label == "high-precision" else 28,
                    "expected": expected,
                }
            )
        for label, left, right, expected in [
            ("rounding-break", ["0.104", "0.104"], ["0.208"], False),
            ("rounding-pass", ["1.10", "2.20"], ["3.30"], True),
        ]:
            cases.append(
                {
                    "id": prefix + label,
                    "split": split,
                    "operation": "totals",
                    "left": left,
                    "right": right,
                    "expected": {"data": {"validated": expected}},
                }
            )
    workbook = Workbook(write_only=True)
    sheet = workbook.create_sheet("Data")
    sheet.append(["reference", "amount"])
    for i in range(1, 100001):
        sheet.append([f"{i:018d}", i])
    workbook.save(root / "bulk.xlsx")
    cases.append(
        {
            "id": "bulk-100k",
            "split": "performance",
            "operation": "bulk",
            "file": "bulk.xlsx",
            "expected": {
                "data": {
                    "rows": 100000,
                    "firstId": "000000000000000001",
                    "lastId": "000000000000100000",
                    "amountTotal": 5000050000.0,
                }
            },
        }
    )
    files = {p.name: digest(p) for p in root.iterdir() if p.is_file()}
    (root / "manifest.json").write_text(
        json.dumps(
            {
                "schema": 1,
                "scope": (
                    "Synthetic read-only contracts; "
                    "not a public benchmark or Desktop UI test"
                ),
                "files": files,
                "cases": cases,
            },
            indent=2,
        )
        + "\n"
    )


def observe(case: dict, root: Path) -> dict:
    from zalos_sheetops.io.read_csv_table import read_csv_table
    from zalos_sheetops.io.read_table import read_table
    from zalos_sheetops.reconcile.exact import reconcile_exact
    from zalos_sheetops.validation.totals import check_totals

    operation = case["operation"]
    if operation == "csv":
        table = read_csv_table(
            root / case["file"],
            encoding="auto",
            delimiter=case["delimiter"],
            max_rows=case.get("maxRows"),
        )
        rows = table["rows"]
        data = {
            "rows": len(rows),
            "first": rows[0],
            "lastId": rows[-1]["reference"],
            "sourceRowsStart": table["sourceRows"][:2],
            "truncated": table["truncated"],
            "rowCount": table["rowCount"],
        }
    elif operation == "table":
        table = read_table(root / case["file"], "Ledger", "row", 1, value_mode="typed")
        data = {k: table[k] for k in ["headers", "rows", "rowCount"]}
    elif operation == "reconcile":
        with localcontext() as context:
            context.prec = case["contextPrecision"]
            report = reconcile_exact(
                case["left"],
                case["right"],
                ["reference"],
                ["reference"],
                "amount",
                "amount",
                "0",
            )
        data = {k: report[k] for k in ["summary", "variance"]}
    elif operation == "totals":
        report = check_totals(case["left"], case["right"], 2)
        data = {"validated": report["validated"]}
    elif operation == "bulk":
        import pyarrow.compute as pc

        from zalos_sheetops.io.read_bulk import read_bulk_table

        batch = read_bulk_table(root / case["file"], "Data", 1)
        data = {
            "rows": batch.num_rows,
            "firstId": batch.column(0)[0].as_py(),
            "lastId": batch.column(0)[-1].as_py(),
            "amountTotal": pc.sum(batch.column(1)).as_py(),
        }
    else:
        raise ValueError("Unknown operation: " + operation)
    return {"data": data}


def worker(case: dict, root: Path) -> dict:
    import zalos_sheetops
    from zalos_sheetops.benchmarks.large_xlsx import _max_rss_bytes
    from zalos_sheetops.errors import SheetOpsError

    started = time.perf_counter()
    try:
        observed = observe(case, root)
    except SheetOpsError as error:
        observed = {"errorCode": error.error_code}
    except Exception as error:
        observed = {"unexpectedError": type(error).__name__, "message": str(error)}
    return {
        "id": case["id"],
        "split": case["split"],
        "operation": case["operation"],
        "passed": grade(case["expected"], observed),
        "observed": observed,
        "seconds": time.perf_counter() - started,
        "maxRssBytes": _max_rss_bytes(),
        "packageSource": str(Path(zalos_sheetops.__file__).resolve()),
    }


def run(root: Path, source: Path, output: Path, repeats: int) -> None:
    source = source.resolve()
    if not (source / "zalos_sheetops" / "__init__.py").is_file():
        raise ValueError(
            "Source must contain zalos_sheetops; use the repository src directory"
        )
    if output.exists():
        raise ValueError("Refusing to overwrite benchmark evidence")
    manifest_path = root / "manifest.json"
    manifest = json.loads(manifest_path.read_text())
    if not all(
        digest(root / name) == expected for name, expected in manifest["files"].items()
    ):
        raise ValueError("Fixture hashes changed")
    source_hashes = {
        str(p.relative_to(source)): digest(p) for p in source.rglob("*.py")
    }
    runner_hash = digest(Path(__file__).resolve())
    records = []
    for repeat in range(repeats):
        cases = (
            manifest["cases"] if repeat % 2 == 0 else list(reversed(manifest["cases"]))
        )
        for case in cases:
            env = {**os.environ, "PYTHONPATH": str(source.resolve())}
            result = subprocess.run(
                [
                    sys.executable,
                    str(Path(__file__).resolve()),
                    "worker",
                    "--root",
                    str(root),
                    "--case",
                    case["id"],
                ],
                env=env,
                text=True,
                capture_output=True,
                timeout=120,
                check=True,
            )
            observation = json.loads(result.stdout)
            if not Path(observation["packageSource"]).is_relative_to(source):
                raise ValueError("Worker imported a different SheetOps source")
            records.append({**observation, "repeat": repeat})
    if not all(
        digest(root / name) == expected for name, expected in manifest["files"].items()
    ):
        raise ValueError("Fixture hashes changed during the benchmark")
    current_source = {
        str(p.relative_to(source)): digest(p) for p in source.rglob("*.py")
    }
    if (
        current_source != source_hashes
        or digest(Path(__file__).resolve()) != runner_hash
    ):
        raise ValueError("Source or benchmark runner changed during execution")
    summary = {}
    for split in ["development", "reserved", "performance"]:
        selected = [x for x in records if x["split"] == split]
        summary[split] = {
            "trials": len(selected),
            "passed": sum(x["passed"] for x in selected),
            "medianSeconds": statistics.median(x["seconds"] for x in selected),
        }
    result = {
        "manifestSha256": digest(manifest_path),
        "sourceSha256": source_hashes,
        "runnerSha256": runner_hash,
        "python": sys.version,
        "repeats": repeats,
        "memoryScope": (
            "Fresh worker process peak RSS including interpreter and imports"
        ),
        "summary": summary,
        "records": records,
    }
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(result, indent=2) + "\n")
    print(json.dumps(summary))


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("command", choices=["prepare", "run", "worker"])
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--source", type=Path)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--repeats", type=int, default=3)
    parser.add_argument("--case")
    args = parser.parse_args()
    if args.command == "prepare":
        prepare(args.root)
    elif args.command == "worker":
        manifest = json.loads((args.root / "manifest.json").read_text())
        case = next(x for x in manifest["cases"] if x["id"] == args.case)
        print(json.dumps(worker(case, args.root)))
    else:
        if args.source is None or args.output is None or args.repeats < 1:
            parser.error("run requires --source, --output and positive --repeats")
        run(args.root, args.source, args.output, args.repeats)


if __name__ == "__main__":
    main()
